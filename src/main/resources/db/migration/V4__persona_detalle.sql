-- Detalle demográfico / laboral de persona (1:1 con TPERSONA)
CREATE TABLE dbo.TPERSONADETALLE (
    IDPERSONADETALLE INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) NOT NULL,
    IDPERSONA INT NOT NULL,
    ESTADOCIVIL VARCHAR(30),
    NACIONALIDAD VARCHAR(60),
    OCUPACION VARCHAR(100),
    NIVELEDUCATIVO VARCHAR(60),
    EMPLEADOR VARCHAR(120),
    INGRESOS DECIMAL(18, 2),
    FCREACION TIMESTAMP,
    FMODIFICACION TIMESTAMP,
    USUARIOCREACION VARCHAR(100),
    USUARIOMODIFICACION VARCHAR(100),
    CONSTRAINT PK_TPERSONADETALLE PRIMARY KEY (IDPERSONADETALLE),
    CONSTRAINT UQ_TPERSONADETALLE_IDPERSONA UNIQUE (IDPERSONA),
    CONSTRAINT FK_TPERSONADETALLE_IDPERSONA FOREIGN KEY (IDPERSONA) REFERENCES dbo.TPERSONA (IDPERSONA)
);

